/**
 * A user-scope re-export stub loads in a real spawned `pi` process on Windows, the shape `pi-subagents` uses for a
 * subagent. Three cases, each with a paired control: the stub loads; the same sentinel at project scope without trust
 * does not (and does with `-a`); editing the target is picked up without rewriting the stub. The sentinel registers a
 * provider whose unique model id `pi --list-models` shows with no network or trust prompt.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { writeUserScopeShim } from "../helpers/session.ts";
import { scratchDirs } from "../helpers/scratch.ts";
import { requirePiOnPath, runPi } from "../helpers/pi.ts";

const scratch = scratchDirs();
const tempDir = scratch.make;

/** A Pi environment with a fresh agent directory, so no saved trust decision can leak into the negative control. */
function freshAgentEnv(agentDir: string): Record<string, string> {
	return {
		...(process.env as Record<string, string>),
		PI_CODING_AGENT_DIR: agentDir,
	};
}

/** The unique model id a given sentinel source registers, for `--list-models` greps. */
function sentinelModelId(tag: string): string {
	return `kypi-safety-spike-${tag}`;
}

/** The sentinel extension source, parameterised on `tag` so the freshness case can change its output. */
function sentinelSource(tag: string): string {
	const modelId = sentinelModelId(tag);
	return [
		'import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";',
		"",
		"// Generated by tests/integration/user-scope-load.test.ts. Lives in a temp dir",
		"// outside this repository -- never committed.",
		"export default function (pi: ExtensionAPI): void {",
		'\tpi.registerCommand("ky-safety-spike", {',
		'\t\tdescription: "04-01 Wave-0 user-scope-load spike sentinel",',
		"\t\thandler: async (_args, ctx) => {",
		`\t\t\tctx.ui.notify("ky-safety-spike loaded (${modelId})", "info");`,
		"\t\t},",
		"\t});",
		"",
		'\tpi.registerProvider("kypi-safety-spike", {',
		'\t\tbaseUrl: "http://127.0.0.1:1/v1",',
		'\t\tapiKey: "unused",',
		'\t\tapi: "openai-completions",',
		"\t\tmodels: [",
		"\t\t\t{",
		`\t\t\t\tid: ${JSON.stringify(modelId)},`,
		'\t\t\t\tname: "04-01 spike sentinel (diagnostic only, not routable)",',
		"\t\t\t\treasoning: false,",
		'\t\t\t\tinput: ["text"],',
		"\t\t\t\tcost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },",
		"\t\t\t\tcontextWindow: 8192,",
		"\t\t\t\tmaxTokens: 1024,",
		"\t\t\t},",
		"\t\t],",
		"\t});",
		"}",
		"",
	].join("\n");
}

/** Write (or overwrite) the sentinel TARGET file the stub re-exports. */
function writeSentinelTarget(path: string, tag: string): void {
	writeFileSync(path, sentinelSource(tag), "utf-8");
}

/** Writes the same sentinel directly at project scope, where the file itself is the entry point. */
function writeProjectScopeSource(cwd: string, name: string, source: string): void {
	const dir = join(cwd, ".pi", "extensions", name);
	mkdirSync(dir, { recursive: true });
	writeFileSync(join(dir, "index.ts"), source, "utf-8");
}

/** Fail loudly, with `pi`'s own stderr, before asserting anything about stdout. */
function assertNoParseError(result: { stderr: string; status: number | null }): void {
	expect(result.status, `pi failed:\n${result.stderr}`).toBe(0);
}

describe("SAFE-11 -- the user-scope re-export stub, proven against a real spawned `pi`", () => {
	beforeAll(() => {
		// Throws rather than skipping -- see tests/helpers/pi.ts's own docstring.
		requirePiOnPath();
	});

	afterAll(scratch.cleanup);

	it("case 1 -- POSITIVE: a user-scope re-export stub loads the sentinel", () => {
		const sentinelDir = tempDir("kypi-sentinel-");
		const sentinelPath = join(sentinelDir, "sentinel.ts");
		writeSentinelTarget(sentinelPath, "positive");

		const agentDir = tempDir("kypi-agentdir-");
		writeUserScopeShim(agentDir, "ky-safety-spike", sentinelPath);

		// An empty cwd, so the user-scope stub is the only possible source; user scope ignores project trust.
		const cwd = tempDir("kypi-cwd-");

		const result = runPi(["--list-models"], { cwd, env: freshAgentEnv(agentDir) });
		assertNoParseError(result);
		expect(
			result.stdout,
			"the re-export stub at <agentDir>/extensions/ky-safety-spike/index.ts must resolve " +
				"through jiti in a REAL spawned pi process and register the sentinel provider",
		).toContain(sentinelModelId("positive"));
	});

	it("case 2 -- NEGATIVE CONTROL: the identical sentinel at PROJECT scope does not load without trust, paired with a positive control", () => {
		const sentinelDir = tempDir("kypi-sentinel-");
		const sentinelPath = join(sentinelDir, "sentinel.ts");
		const source = sentinelSource("project-scope");
		writeSentinelTarget(sentinelPath, "project-scope");

		const projectCwd = tempDir("kypi-project-");
		writeProjectScopeSource(projectCwd, "ky-safety-spike", source);

		// One agent dir for both runs: only -a differs, so only the trust gate can explain a different outcome.
		const agentDir = tempDir("kypi-agentdir-");
		const env = freshAgentEnv(agentDir);

		const gated = runPi(["--list-models"], { cwd: projectCwd, env });
		assertNoParseError(gated);
		expect(
			gated.stdout,
			"project trust defaults to `ask`, and non-interactive modes never prompt -- so without " +
				"-a the project-scoped sentinel must be ignored. This is Pitfall 15's exact mechanism: " +
				"a safety extension shipped only at project scope silently never loads in a headless " +
				"subagent, and the absence looks identical to 'nothing dangerous happened'",
		).not.toContain(sentinelModelId("project-scope"));

		// Paired positive: without it the absence above could mean a broken fixture.
		const approved = runPi(["-a", "--list-models"], { cwd: projectCwd, env });
		assertNoParseError(approved);
		expect(
			approved.stdout,
			"adding -a and changing nothing else must flip the verdict; if it does not, the absence " +
				"above proves nothing about the trust gate",
		).toContain(sentinelModelId("project-scope"));
	});

	it("case 3 -- FRESHNESS: editing the sentinel TARGET picks up new content with no change to the stub", () => {
		const sentinelDir = tempDir("kypi-sentinel-");
		const sentinelPath = join(sentinelDir, "sentinel.ts");
		writeSentinelTarget(sentinelPath, "fresh-v1");

		const agentDir = tempDir("kypi-agentdir-");
		// The stub is written ONCE. Only the target file changes below.
		writeUserScopeShim(agentDir, "ky-safety-spike", sentinelPath);

		const cwd = tempDir("kypi-cwd-");
		const env = freshAgentEnv(agentDir);

		const before = runPi(["--list-models"], { cwd, env });
		assertNoParseError(before);
		expect(before.stdout, "the first run must see the v1 sentinel").toContain(sentinelModelId("fresh-v1"));

		// Overwrite ONLY the target the stub re-exports. The stub file itself
		// (<agentDir>/extensions/ky-safety-spike/index.ts) is never touched again.
		writeSentinelTarget(sentinelPath, "fresh-v2");

		const after = runPi(["--list-models"], { cwd, env });
		assertNoParseError(after);
		expect(
			after.stdout,
			"a fresh pi process must re-resolve the stub's import and see the EDITED target -- jiti " +
				"has no cross-process cache, so this is what makes 'one copy of the logic' true rather " +
				"than aspirational",
		).toContain(sentinelModelId("fresh-v2"));
		expect(
			after.stdout,
			"and the v1 content must be genuinely gone, not merely accumulated alongside v2",
		).not.toContain(sentinelModelId("fresh-v1"));
	});
});
